#!/usr/bin/env python3
"""Generates lib/i18n/locales/bg-features.ts and merges en/tr/ro overrides.

Source of truth for new UI strings: scripts/i18n-features.json
  { "section.key": ["bg", "en", "tr", "ro"], ... }
Run: python3 scripts/i18n-features.py
"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
spec = json.loads((root / "scripts/i18n-features.json").read_text())

def nest(pairs):
    tree = {}
    for path, value in pairs:
        node = tree
        parts = path.split(".")
        for part in parts[:-1]:
            node = node.setdefault(part, {})
        node[parts[-1]] = value
    return tree

def ts(value, indent=0):
    pad = "  " * indent
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    lines = ["{"]
    for k, v in value.items():
        lines.append(f"{pad}  {k}: {ts(v, indent + 1)},")
    lines.append(pad + "}")
    return "\n".join(lines)

bg_tree = nest((p, v[0]) for p, v in sorted(spec.items()))
out = "/** New UI strings (garage, saved-route editing, weather places, …). Generated by scripts/i18n-features.py. */\nexport const bgFeatures = " + ts(bg_tree) + " as const;\n"
(root / "lib/i18n/locales/bg-features.ts").write_text(out)

def merge(dst, src):
    for k, v in src.items():
        if isinstance(v, dict):
            merge(dst.setdefault(k, {}), v)
        else:
            dst[k] = v

for idx, code in ((1, "en"), (2, "tr"), (3, "ro")):
    f = root / f"lib/i18n/locales/translations/{code}-overrides.json"
    data = json.loads(f.read_text())
    merge(data, nest((p, v[idx]) for p, v in sorted(spec.items())))
    f.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n")
print("ok", len(spec))
