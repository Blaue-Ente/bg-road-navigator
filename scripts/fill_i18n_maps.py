def apply_phrases(text: str, phrases: list[tuple[str, str]]) -> str:
    out = text
    for src, dst in sorted(phrases, key=lambda p: -len(p[0])):
        out = out.replace(src, dst)
    return out


def translate(text: str, exact: dict[str, str], phrases: list[tuple[str, str]], lang: str) -> str:
    if text in exact:
        return exact[text]
    out = apply_phrases(text, phrases)
    if CYR.search(out):
        if lang == "en":
            out = out.translate(BG_TO_LATIN)
            out = re.sub(r"\s+", " ", out).strip()
    if out == text and CYR.search(text):
        out = text.translate(BG_TO_LATIN)
    if out == text and lang != "bg" and CYR.search(text):
        out = f"[{lang}] {text.translate(BG_TO_LATIN)}"
    return out


def load_quality() -> dict[str, dict[str, str]]:
    path = ROOT / "lib/i18n/locales/translations/quality-overrides.json"
    if not path.exists():
        return {"en": {}, "tr": {}, "ro": {}}
    return json.loads(path.read_text("utf8"))


def main() -> None:
    out_dir = ROOT / "lib/i18n/locales/translations"
    out_dir.mkdir(parents=True, exist_ok=True)
    quality = load_quality()
    for lang, exact, phrases in (
        ("en", EXACT_EN, PHRASES_EN),
        ("tr", EXACT_TR, PHRASES_TR),
        ("ro", EXACT_RO, PHRASES_RO),
    ):
        boosted = {**exact, **quality.get(lang, {})}
        mapped = {bg: translate(bg, boosted, phrases, lang) for bg in UNIQUE}
        path = out_dir / f"{lang}-by-bg.json"
        path.write_text(json.dumps(mapped, ensure_ascii=False, indent=2), "utf8")
        cyrillic_left = sum(1 for bg, loc in mapped.items() if bg == loc and CYR.search(bg))
        print(lang, "entries", len(mapped), "still identical+cyrillic", cyrillic_left)
        if cyrillic_left:
            sample = [bg for bg, loc in mapped.items() if bg == loc and CYR.search(bg)][:5]
            print("  sample:", sample)


if __name__ == "__main__":
    main()